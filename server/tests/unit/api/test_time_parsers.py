def _run(f):
    try:
        return f()
    except HTTPException as e:
        return ("HTTP", e.status_code, e.detail)
    except ValueError as e:
        return ("ValueError", str(e))


@pytest.mark.parametrize("value", list(TABLE))
def test_parsers_pinned(value: str) -> None:
    due = resolve_due(value, date(2026, 10, 18))
    got = (_run(lambda: parse_ts(value)), _run(lambda: parse_time(value, "at")),
           _run(lambda: parse_when(value, LIS)), _run(lambda: parse_when(value, LIS, end=True)),
           _run(lambda: parse_when(value, NY)), _run(lambda: parse_when(value, NY, end=True)),
           due.isoformat() if due else None)
    assert got == TABLE[value]


@pytest.mark.parametrize("ts", [None, 0, 0.0, 1792317600, 1792317600.25, -1.5, 4102444800])
def test_iso_pinned(ts: float | None) -> None:
    want = None if ts is None else datetime.fromtimestamp(ts, UTC).isoformat()
    assert iso(ts) == _iso(ts) == want


def test_iso_examples() -> None:
    assert iso(1792317600) == "2026-10-18T10:00:00+00:00"
    assert iso(1792317600.25) == "2026-10-18T10:00:00.250000+00:00"
    assert iso(0) == "1970-01-01T00:00:00+00:00"
